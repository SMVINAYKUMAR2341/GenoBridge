import { NextResponse } from 'next/server'

export async function POST(request: Request) {
  try {
    const data = await request.json()
    const { patientId = 'SYN-STANDALONE', physicianName = 'Attending Clinician', pathway = 'Clinical Genetics', evaluation = {} } = data

    const risk = String(evaluation.risk_level || evaluation.outcome || 'ROUTINE').toUpperCase()
    const confidence = Math.round(Number(evaluation.confidence_score || 0.98) * 100)
    const ruleId = evaluation.matched_rule_id || 'STD-CARE-00'
    const guideline = evaluation.guideline || 'ACOG / NCCN / ACMG / ASRM Clinical Practice Guidelines'
    const action = evaluation.action || evaluation.explanation || 'Standard clinical genetics evaluation.'
    const cpt = (evaluation.cpt_codes || []).join(', ') || '96040'
    const icd10 = (evaluation.icd10_codes || []).join(', ') || 'Z34.90'

    // Clean vector PDF generation (minimalist valid PDF 1.4 stream)
    const pdfLines = [
      '%PDF-1.4',
      '1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj',
      '2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj',
      '3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >> endobj',
      '4 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj',
      '5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >> endobj',
    ]

    const textOps = [
      'BT',
      '/F2 16 Tf',
      '40 740 Td',
      '(GENOBRIDGE CLINICAL GENETICS DSS) Tj',
      '/F1 8 Tf',
      '0 -14 Td',
      '(FDA SaMD DETERMINISTIC EVALUATION BRIEF - ACOG / NCCN / ACMG / ASRM) Tj',
      '0 -24 Td',
      '/F2 10 Tf',
      `(${escapePdf(`CASE REF: ${patientId}  |  ATTENDING: Dr. ${physicianName}  |  DATE: ${new Date().toISOString().slice(0, 10)}`)}) Tj`,
      '0 -20 Td',
      '/F2 12 Tf',
      `(${escapePdf(`TRIAGE LEVEL: ${risk}  (CONFIDENCE MATCH: ${confidence}%)`)}) Tj`,
      '0 -18 Td',
      '/F1 9 Tf',
      `(${escapePdf(`RECOMMENDED ACTION: ${action.slice(0, 95)}`)}) Tj`,
      '0 -14 Td',
      `(${escapePdf(action.length > 95 ? action.slice(95, 190) : '')}) Tj`,
      '0 -24 Td',
      '/F2 10 Tf',
      '(GLASS-BOX CLINICAL RATIONALE & GROUND TRUTH CITATIONS) Tj',
      '0 -15 Td',
      '/F1 9 Tf',
      `(${escapePdf(`• Matched Rule ID: ${ruleId}`)}) Tj`,
      '0 -13 Td',
      `(${escapePdf(`• Statutory Guideline: ${guideline}`)}) Tj`,
      '0 -13 Td',
      `(${escapePdf(`• Applicable CPT Codes: ${cpt}`)}) Tj`,
      '0 -13 Td',
      `(${escapePdf(`• Diagnostic ICD-10 Codes: ${icd10}`)}) Tj`,
      '0 -24 Td',
      '/F2 10 Tf',
      '(STATUTORY CLINICAL SAFETY NOTICE) Tj',
      '0 -14 Td',
      '/F1 7 Tf',
      '(This evaluation is generated by a deterministic rule-based decision support algorithm.) Tj',
      '0 -10 Td',
      '(It does not constitute an independent diagnosis. Attending physicians retain exclusive responsibility.) Tj',
      'ET',
    ]

    const streamContent = textOps.join('\n')
    const streamObj = `6 0 obj << /Length ${Buffer.byteLength(streamContent, 'utf-8')} >>\nstream\n${streamContent}\nendstream\nendobj`

    pdfLines.push(streamObj)
    pdfLines.push('xref')
    pdfLines.push('0 7')
    pdfLines.push('0000000000 65535 f ')
    pdfLines.push('0000000009 00000 n ')
    pdfLines.push('0000000058 00000 n ')
    pdfLines.push('0000000115 00000 n ')
    pdfLines.push('0000000261 00000 n ')
    pdfLines.push('0000000330 00000 n ')
    pdfLines.push('0000000404 00000 n ')
    pdfLines.push('trailer << /Size 7 /Root 1 0 R >>')
    pdfLines.push('startxref')
    pdfLines.push('600')
    pdfLines.push('%%EOF')

    const pdfBuffer = Buffer.from(pdfLines.join('\n'), 'utf-8')

    return new NextResponse(pdfBuffer, {
      status: 200,
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="Clinical_Brief_${patientId}.pdf"`,
      },
    })
  } catch (err: any) {
    return NextResponse.json({ message: err.message || 'Error generating PDF' }, { status: 500 })
  }
}

function escapePdf(str: string): string {
  return str.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)')
}
